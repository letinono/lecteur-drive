// Service worker : met en cache UNIQUEMENT l'interface de l'app (HTML/CSS/JS/icônes).
// Il ne touche jamais aux requêtes vers Google (Drive, connexion) ni aux fichiers audio.
const VERSION = '__VERSION__';
const CACHE = 'lecteur-ui-' + VERSION;
const FILES = __FILES__;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('lecteur-ui-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return; // Google, etc. : on laisse passer
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./');
      return fetch(req);
    }),
  );
});
